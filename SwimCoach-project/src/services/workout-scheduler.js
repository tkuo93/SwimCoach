/**
 * Weekly auto-generation scheduler.
 *
 * On-demand trigger: when a user loads their workouts (GET /api/workouts), we
 * check if they have workouts planned for the *upcoming week* (next Monday–Sunday).
 * If they have zero workouts, we generate a full week's program. If they have
 * some, we fill in only the missing schedule days.
 *
 * This runs on free-tier hosts (Render/Fly) where in-process cron can't
 * fire reliably because the container sleeps when idle. By piggybacking
 * on the existing authenticated GET /api/workouts call, we ensure the check
 * runs whenever a user interacts with the app.
 *
 * The "already generated this week" guard is persisted on the SwimmerProfile
 * document (`lastAutoGeneratedWeek`) so it survives container restarts.
 * On free-tier hosts the container may sleep and wake from a fresh process,
 * which would wipe any in-memory cache — so we must use the database.
 */

const Workout = require('../models/Workout');
const SwimmerProfile = require('../models/SwimmerProfile');
const { generateWeeklyProgram } = require('./program-generator');

// ─── In-memory secondary guard (supplements DB guard) ───────────────────────
// swimmerId -> last check week key (YYYY-WW, ISO week of the TARGET week)
// This prevents redundant DB writes within the same process when the user
// loads workouts multiple times. The DB field is the source of truth;
// this cache is just an optimization.
const lastCheckCache = new Map();

// ─── Configuration ─────────────────────────────────────────────────────────
// Fallback completion threshold for mid-week generation (when before last scheduled day)
// Can be overridden via env var AUTO_GEN_MIN_COMPLETION_RATE
const MIN_COMPLETION_RATE = parseFloat(process.env.AUTO_GEN_MIN_COMPLETION_RATE) || 0.8;

// Day order for finding the last scheduled day of the week
const DAY_ORDER = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
const DAY_TO_NUM = { sunday: 0, monday: 1, tuesday: 2, wednesday: 3, thursday: 4, friday: 5, saturday: 6 };

/**
 * Compute the Monday-Sunday date range for the *upcoming* week
 * (next Monday–Sunday), regardless of what day it is today.
 *
 * Always targets next week:
 * - If today is Monday, next week starts the following Monday.
 * - If today is Sunday, next week starts tomorrow (Monday).
 *
 * @param {Date} [refDate] - Reference date (defaults to now)
 * @returns {{ start: Date, end: Date }} - Monday 00:00 to Sunday 23:59:59.999
 */
function getUpcomingWeekRange(refDate) {
  const today = new Date(refDate || new Date());
  today.setUTCHours(0, 0, 0, 0);
  const dayOfWeek = today.getUTCDay(); // 0 = Sunday, 1 = Monday, ..., 6 = Saturday

  // Days from today until next Monday (always > 0, so we always go forward).
  // On Monday, (8 - 1) % 7 = 0, so we need || 7 to push to next Monday.
  const daysUntilMonday = (8 - dayOfWeek) % 7 || 7;
  const monday = new Date(today);
  monday.setUTCDate(today.getUTCDate() + daysUntilMonday);
  monday.setUTCHours(0, 0, 0, 0);

  const sunday = new Date(monday);
  sunday.setUTCDate(monday.getUTCDate() + 6);
  sunday.setUTCHours(23, 59, 59, 999);

  return { start: monday, end: sunday };
}

/**
 * Get the ISO week key for a date (e.g., "2025-W01").
 * Used as the cache key to prevent duplicate weekly checks.
 */
function getISOWeekKey(date) {
  const d = new Date(date || new Date());
  d.setHours(0, 0, 0, 0);
  d.setDate(d.getDate() + 3 - (d.getDay() + 6) % 7);
  const week1 = new Date(d.getFullYear(), 0, 4);
  const weekNumber = 1 + Math.round(
    ((d.getTime() - week1.getTime()) / 86400000 - 3 + ((week1.getDay() + 6) % 7)) / 7
  );
  return `${d.getFullYear()}-W${String(weekNumber).padStart(2, '0')}`;
}

/**
 * Check if a swimmer has any workouts scheduled in the given week.
 *
 * @param {string} swimmerId - Mongoose ObjectId as string
 * @param {Date} weekStart - Monday of the target week
 * @param {Date} weekEnd - Sunday end of the target week
 * @returns {Promise<number>} - Count of workouts in the week (-1 on error)
 */
async function countWorkoutsInWeek(swimmerId, weekStart, weekEnd) {
  try {
    return await Workout.countDocuments({
      swimmerId,
      date: { $gte: weekStart, $lt: new Date(weekEnd.getTime() + 1) }, // exclusive end
    });
  } catch (err) {
    console.error(`[Scheduler] Failed to count workouts for swimmer ${swimmerId}:`, err.message);
    return -1; // signal error
  }
}

/**
 * Fetch the dates of existing workouts in the given week.
 *
 * @param {string} swimmerId - Mongoose ObjectId as string
 * @param {Date} weekStart - Monday of the target week
 * @param {Date} weekEnd - Sunday end of the target week
 * @returns {Promise<Date[]>} - Array of workout dates in the week (empty on error)
 */
async function getExistingWorkoutDates(swimmerId, weekStart, weekEnd) {
  try {
    const docs = await Workout.find({
      swimmerId,
      date: { $gte: weekStart, $lt: new Date(weekEnd.getTime() + 1) },
    }).select('date -_id').lean();
    return docs.map(d => new Date(d.date));
  } catch (err) {
    console.error(`[Scheduler] Failed to fetch workout dates for swimmer ${swimmerId}:`, err.message);
    return [];
  }
}

/**
 * Get the current week's date range (this Monday–Sunday).
 * Unlike getUpcomingWeekRange, this returns the week containing the refDate.
 *
 * @param {Date} refDate - Reference date
 * @returns {{ start: Date, end: Date }} - Monday 00:00 to Sunday 23:59:59.999
 */
function getCurrentWeekRange(refDate) {
  const today = new Date(refDate);
  today.setUTCHours(0, 0, 0, 0);
  const dayOfWeek = today.getUTCDay(); // 0 = Sunday, 1 = Monday, ..., 6 = Saturday

  // Days from today back to this Monday
  const daysSinceMonday = (dayOfWeek + 6) % 7; // Monday=0, Sunday=6
  const monday = new Date(today);
  monday.setUTCDate(today.getUTCDate() - daysSinceMonday);
  monday.setUTCHours(0, 0, 0, 0);

  const sunday = new Date(monday);
  sunday.setUTCDate(monday.getUTCDate() + 6);
  sunday.setUTCHours(23, 59, 59, 999);

  return { start: monday, end: sunday };
}

/**
 * Determine the scheduled days for the current week based on the profile.
 * Returns an array of day names (lowercase) that have pool or gym sessions.
 */
function getScheduledDays(profile) {
  const poolDays = (profile.trainingSchedule?.poolDays || []).map(d => d.toLowerCase());
  const gymDays = (profile.trainingSchedule?.gymDays || []).map(d => d.toLowerCase());

  // If no explicit days set, use defaults from session counts
  if (poolDays.length === 0 && gymDays.length === 0) {
    const poolCount = profile.trainingSchedule?.weeklyPoolSessions || 0;
    const gymCount = profile.trainingSchedule?.weeklyGymSessions || 0;
    // Only add default days if sessions > 0
    const defaultPoolDays = poolCount > 0 ? ['monday', 'wednesday', 'friday'].slice(0, poolCount) : [];
    const defaultGymDays = gymCount > 0 ? ['tuesday', 'thursday'].slice(0, gymCount) : [];
    return [...defaultPoolDays, ...defaultGymDays];
  }

  return [...new Set([...poolDays, ...gymDays])];
}

/**
 * Check if we should generate next week's workouts.
 * Generates if:
 *  1. We're on or past the last scheduled day of the current week, OR
 *  2. No workouts exist for the current week (first week or missed generation)
 *  3. (Fallback) Completion rate meets threshold for mid-week generation
 *
 * @param {string} swimmerId - Mongoose ObjectId as string
 * @param {Object} profile - SwimmerProfile document
 * @param {Date} refDate - Reference date (defaults to now)
 * @returns {Promise<{ shouldGenerate: boolean, reason: string, completionRate: number }>}
 */
async function isCurrentWeekSufficientlyComplete(swimmerId, profile, refDate) {
  const { start: currentWeekStart, end: currentWeekEnd } = getCurrentWeekRange(refDate);

  // Get scheduled days for this week
  const scheduledDays = getScheduledDays(profile);
  if (scheduledDays.length === 0) {
    return { shouldGenerate: true, reason: 'No scheduled days configured', completionRate: 1 };
  }

  // Find the last scheduled day of the week (0=Sunday ... 6=Saturday)
  let lastScheduledDayNum = -1;
  for (const day of scheduledDays) {
    const dayNum = DAY_TO_NUM[day];
    if (dayNum > lastScheduledDayNum) lastScheduledDayNum = dayNum;
  }

  // Convert Sunday (0) to 7 for proper day-of-week comparison within Mon-Sun week
  const today = new Date(refDate);
  today.setUTCHours(0, 0, 0, 0);
  const currentDayForComparison = today.getUTCDay() === 0 ? 7 : today.getUTCDay();
  const lastScheduledDayForComparison = lastScheduledDayNum === 0 ? 7 : lastScheduledDayNum;

  // Rule 1: On or past the last scheduled day → generate
  if (currentDayForComparison >= lastScheduledDayForComparison) {
    return {
      shouldGenerate: true,
      reason: `On/past last scheduled day (${Object.keys(DAY_TO_NUM).find(k => DAY_TO_NUM[k] === lastScheduledDayNum)})`,
      completionRate: 1
    };
  }

  // Rule 2: No workouts exist for current week → generate (first week or recovery)
  try {
    const currentWeekWorkouts = await Workout.countDocuments({
      swimmerId,
      date: { $gte: currentWeekStart, $lt: new Date(currentWeekEnd.getTime() + 1) }
    });

    if (currentWeekWorkouts === 0) {
      return {
        shouldGenerate: true,
        reason: 'No workouts scheduled for current week',
        completionRate: 0
      };
    }
  } catch (err) {
    console.error(`[Scheduler] Failed to count current week workouts for ${swimmerId}:`, err.message);
    // Fail open
    return { shouldGenerate: true, reason: 'Error checking current week, allowing generation', completionRate: 0 };
  }

  // Rule 3: Mid-week fallback - check completion threshold (for users who want early generation)
  // Only applies if workouts exist but we're before last scheduled day
  try {
    const completedWorkouts = await Workout.find({
      swimmerId,
      date: { $gte: currentWeekStart, $lt: new Date(currentWeekEnd.getTime() + 1) },
      'userFeedback.completedAt': { $exists: true, $ne: null }
    }).select('date -_id').lean();

    const completedCount = completedWorkouts.length;
    const totalScheduled = scheduledDays.length;
    const completionRate = totalScheduled > 0 ? completedCount / totalScheduled : 1;

    if (completionRate >= MIN_COMPLETION_RATE) {
      return {
        shouldGenerate: true,
        reason: `Completion rate ${Math.round(completionRate * 100)}% meets threshold ${Math.round(MIN_COMPLETION_RATE * 100)}%`,
        completionRate
      };
    }

    return {
      shouldGenerate: false,
      reason: `Before last scheduled day, completion rate ${Math.round(completionRate * 100)}% below threshold ${Math.round(MIN_COMPLETION_RATE * 100)}%`,
      completionRate
    };
  } catch (err) {
    console.error(`[Scheduler] Failed to check completion rate for ${swimmerId}:`, err.message);
    // Fail open
    return { shouldGenerate: true, reason: 'Error checking completion, allowing generation', completionRate: 0 };
  }
}

/**
 * Main entry point: check whether a swimmer needs an auto-generated weekly program.
 *
 * Called from the authenticated GET /api/workouts route (via setImmediate).
 * Runs at most once per swimmer per ISO week of the TARGET week (next week),
 * with the guard persisted in the database so it survives container restarts.
 *
 * Logic (always targets next week, Mon–Sun):
 *  1. Check the upcoming week (next Monday–Sunday) for existing workouts.
 *  2. If zero workouts, generate a full week.
 *  3. If some exist, fill in only the missing schedule days.
 *
 * @param {string} swimmerId - Mongoose ObjectId as string
 * @param {Date} [now] - Override current time (for testing)
 */
async function checkAndGenerateUpcomingWeek(swimmerId, now) {
  const refDate = new Date(now || new Date());
  // Normalize to UTC midnight so the generator and scheduler compute the same
  // week range regardless of the server's local timezone.
  refDate.setUTCHours(0, 0, 0, 0);

  // Compute the target week (always next Monday–Sunday)
  const { start: weekStart, end: weekEnd } = getUpcomingWeekRange(refDate);

  // Weekly guard — prevent duplicate runs within the same target ISO week.
  // We key on the ISO week of the *target* week, not today,
  // so Sunday and Monday both targeting the same upcoming week are guarded.
  const weekKey = getISOWeekKey(weekStart);

  // ─── DB-backed guard (source of truth) ──
  // Persists across container restarts / process reloads.
  const profile = await SwimmerProfile.findById(swimmerId);
  if (!profile) {
    return { skipped: true, reason: 'Profile not found' };
  }

  if (profile.lastAutoGeneratedWeek === weekKey) {
    return { skipped: true, reason: 'Already auto-generated this week' };
  }

  // ─── In-memory guard (optimization) ──
  // Avoids re-querying the DB on repeated requests within the same process.
  if (lastCheckCache.get(swimmerId) === weekKey) {
    return { skipped: true, reason: 'Already checked this week' };
  }
  lastCheckCache.set(swimmerId, weekKey);

  // Check if current week is sufficiently complete before generating next week
  const completionCheck = await isCurrentWeekSufficientlyComplete(swimmerId, profile, refDate);
  if (!completionCheck.shouldGenerate) {
    console.log(`[Scheduler] Skipping generation for ${swimmerId}: ${completionCheck.reason}`);
    return { skipped: true, reason: completionCheck.reason, completionRate: completionCheck.completionRate };
  }
  console.log(`[Scheduler] Current week check passed for ${swimmerId}: ${completionCheck.reason}`);

  // Check for existing workouts in the target (upcoming) week
  const existingCount = await countWorkoutsInWeek(swimmerId, weekStart, weekEnd);
  if (existingCount < 0) {
    return { skipped: true, reason: 'DB query failed' };
  }

  // If workouts exist, fetch their dates so we can fill in only the missing days
  let existingDates = [];
  if (existingCount > 0) {
    existingDates = await getExistingWorkoutDates(swimmerId, weekStart, weekEnd);
    console.log(`[Scheduler] Swimmer ${swimmerId} already has ${existingCount} workout(s) for ${weekStart.toISOString().split('T')[0]} week — filling in missing days`);
  }

  // Generate workouts for the upcoming week
  console.log(`[Scheduler] Generating ${existingCount === 0 ? 'full week' : 'missing days'} for swimmer ${swimmerId} (weekStart: ${weekStart.toISOString().split('T')[0]})`);
  try {
    // weekStartOffset is always 1 (next week), relative to refDate in the generator.
    // Pass refDate so the generator computes the same week range we just computed.
    const result = await generateWeeklyProgram(profile, {
      programPeriod: 'weekly',
      weekStartOffset: 1,
      existingDates: existingDates.map(d => d.toISOString()),
    }, { refDate: refDate });

    // Persist the generated week on the profile so we don't re-generate after
    // a container restart (the in-memory cache would be wiped).
    profile.lastAutoGeneratedWeek = weekKey;
    await profile.save();

    console.log(`[Scheduler] Generated ${result.generatedCount}/${result.totalSessions} workouts for swimmer ${swimmerId} — marked week ${weekKey} as generated`);
    return { generated: true, programId: result.programId, count: result.generatedCount, total: result.totalSessions };
  } catch (err) {
    console.error(`[Scheduler] Failed to generate program for swimmer ${swimmerId}:`, err.message);
    return { error: err.message };
  }
}

/**
 * Clear the in-memory cache. Useful for testing.
 * Note: this does NOT clear the DB-backed guard — use a DB migration or
 * direct profile update for that in production.
 */
function clearCache() {
  lastCheckCache.clear();
}

module.exports = {
  checkAndGenerateUpcomingWeek,
  getUpcomingWeekRange,
  getCurrentWeekRange,
  getScheduledDays,
  isCurrentWeekSufficientlyComplete,
  countWorkoutsInWeek,
  getExistingWorkoutDates,
  getISOWeekKey,
  clearCache,
  // Exported for testing
  lastCheckCache,
};
